#!/usr/bin/env python3
"""Work out the Chapter 5 board from the world map.

Reads assets/art/world_map.png (360 x 180, one pixel a degree) and writes
src/data/world.js: a 24 x 12 grid of 15-degree cells, each sea, land, ice or
a city, plus where the first spire stands.

    python3 tools/art/build.py     # first, if the map art changed
    python3 tools/world/build.py
"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CELL = 15
# Roughly where the world's big cities are (longitude, latitude). Each lights
# the nearest land cell.
CITIES = [(-74, 41), (-118, 34), (-99, 19), (-47, -23), (-58, -35), (0, 51), (12, 48), (37, 56), (31, 30), (4, 7),
          (28, -26), (77, 28), (116, 40), (139, 36), (107, -6), (151, -34), (46, 24), (-123, 49)]
START = (-83, 40)  # Riverbend, Ohio

im = np.asarray(Image.open(os.path.join(ROOT, 'assets', 'art', 'world_map.png')).convert('RGB')).astype(int)
r, g, b = im[..., 0], im[..., 1], im[..., 2]
sea = (b > r + 25) & (b > g + 10)
ice = (r > 185) & (g > 195) & (b > 200) & ~sea
cols, rows = 360 // CELL, 180 // CELL
grid = [['.'] * cols for _ in range(rows)]
for j in range(rows):
    for i in range(cols):
        blk_sea = sea[j * CELL:(j + 1) * CELL, i * CELL:(i + 1) * CELL].mean()
        blk_ice = ice[j * CELL:(j + 1) * CELL, i * CELL:(i + 1) * CELL].mean()
        if blk_ice > 0.35 or (j in (0, rows - 1) and blk_sea < 0.6):
            grid[j][i] = 'i'
        elif blk_sea < 0.62:
            grid[j][i] = '#'


def cell_of(lon, lat):
    return int((lon + 180) // CELL) % cols, min(rows - 1, int((90 - lat) // CELL))


def nearest_land(c, r):
    best = None
    for j in range(rows):
        for i in range(cols):
            if grid[j][i] != '#':
                continue
            dx = min(abs(i - c), cols - abs(i - c))
            d = dx * dx + (j - r) ** 2
            if best is None or d < best[0]:
                best = (d, i, j)
    return best[1], best[2]


sc, sr = nearest_land(*cell_of(*START))
for lon, lat in CITIES:
    c, r_ = nearest_land(*cell_of(lon, lat))
    if (c, r_) != (sc, sr):
        grid[r_][c] = 'C'

lines = [''.join(row) for row in grid]
with open(os.path.join(ROOT, 'src', 'data', 'world.js'), 'w') as f:
    f.write('// Generated by tools/world/build.py from assets/art/world_map.png. Do not edit.\n')
    f.write('// 24 x 12 cells of 15 degrees: . sea, # open land, C a city, i ice.\n')
    f.write('(function (M) {\n  M.WORLD_GRID = {\n    start: [%d, %d],\n    rows: [\n' % (sc, sr))
    for ln in lines:
        f.write("      '%s',\n" % ln)
    f.write('    ],\n  };\n})(window.MORE = window.MORE || {});\n')
print('\n'.join(lines))
print('start', sc, sr, 'land', sum(l.count('#') for l in lines), 'cities', sum(l.count('C') for l in lines))
