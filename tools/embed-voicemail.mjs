// Regenerates the embedded audio from assets/audio/:
//   src/data/voicemail-data.js   the cold open's voicemail (ruth_voicemail.mp3)
//   src/data/voice-clips.js      later voicemails, by name (ruth_<name>.mp3)
// Embedding the clips as base64 lets the game decode them with WebAudio even
// when play.html is opened straight from disk (file://), where fetch() is blocked.
//
//   node tools/embed-voicemail.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mp3 = readFileSync(join(root, 'assets/audio/ruth_voicemail.mp3'));
const out = `// Generated by tools/embed-voicemail.mjs from assets/audio/ruth_voicemail.mp3. Do not edit.
(function (M) {
  M.VOICEMAIL_B64 = '${mp3.toString('base64')}';
})(window.MORE = window.MORE || {});
`;
writeFileSync(join(root, 'src/data/voicemail-data.js'), out);
console.log(`wrote src/data/voicemail-data.js (${mp3.length} bytes of audio)`);

// Later voicemails. The name is what a chapter's script asks for.
const CLIPS = ['ch3_school', 'ch3_meeting', 'ch4'];
const lines = CLIPS.map((name) => `    ${name}: '${readFileSync(join(root, `assets/audio/ruth_${name}.mp3`)).toString('base64')}',`);
writeFileSync(
  join(root, 'src/data/voice-clips.js'),
  `// Generated by tools/embed-voicemail.mjs from assets/audio/ruth_*.mp3. Do not edit.
(function (M) {
  M.VOICE_CLIPS = {
${lines.join('\n')}
  };
})(window.MORE = window.MORE || {});
`
);
console.log(`wrote src/data/voice-clips.js (${CLIPS.length} clips)`);
